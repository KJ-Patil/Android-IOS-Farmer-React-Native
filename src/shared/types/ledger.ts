import { Timestamp } from 'firebase/firestore';

export type TransactionType = 'income' | 'expense';
export type LedgerType = 'personal' | 'agriculture' | 'party' | 'custom' | 'dairy';
export type PaymentMode = 'cash' | 'bank' | 'upi' | 'credit' | 'cheque';
export type IncomeCategory = 'crop_sale' | 'dairy' | 'loan' | 'other';

export interface CropSaleDetails {
  plotId: string;
  plotName: string;
  cropId: string;
  cropName: string;
  buyerName: string;
  quantity: number;
  quantityUnit: string;
  ratePerUnit: number;
  grossAmount: number;
  hamaliDeduction?: number;
  transportDeduction?: number;
  otherDeduction?: number;
  totalDeductions: number;
  netAmount: number;
}

export interface DairyDetails {
  productType: 'milk' | 'ghee' | 'paneer' | 'curd' | 'buttermilk' | 'khava' | 'animal_sale' | 'dung' | 'other';
  quantity: number;
  unit: string;
  ratePerUnit: number;
}

export interface LoanDetails {
  loanType: 'crop_loan' | 'term_loan' | 'tractor_loan' | 'gold_loan' | 'personal_loan';
  sanctionAmount: number;
  processingFee: number;
  interestRate: number;
  tenureMonths: number;
  emiFrequency: 'monthly' | 'yearly' | 'half_yearly';
  firstInstallmentDate: string;
  dueDate: string;
  netReceived: number;
}

export interface OtherIncomeDetails {
  subtype: 'subsidy' | 'insurance_claim' | 'tractor_rent' | 'implements_rent' | 'water_sale' | 'saplings_sale' | 'seeds_sale' | 'organic_manure_sale' | 'wages' | 'interest' | 'commission' | 'custom';
}

export interface EditHistoryRecord {
  editedAt: string;
  editedFields: string[];
  previousValues: Record<string, any>;
}

export interface PaymentRecord {
  id: string;
  amount: number;
  date: string;
  paymentMode: PaymentMode;
  notes?: string;
  createdAt: string;
}

export interface Attachment {
  name: string;
  type: string;
  dataUrl: string;
  size: number;
}

export interface Transaction {
  id: string;
  type: TransactionType;
  ledgerType: LedgerType;
  category: string;
  amount: number;
  date: string;
  paymentMode: PaymentMode;
  partyName?: string;
  plotId?: string;
  plotName?: string;
  cropId?: string;
  cropName?: string;
  cropSeason?: string;
  billNumber?: string;
  dueDate?: string;
  pendingAmount?: number;
  notes?: string;
  items?: string;
  gstAmount?: number;
  attachment?: Attachment;
  voiceNoteUrl?: string;
  incomeCategory?: IncomeCategory;
  cropSaleDetails?: CropSaleDetails;
  dairyDetails?: DairyDetails;
  loanDetails?: LoanDetails;
  otherIncomeDetails?: OtherIncomeDetails;
  grossAmount?: number;
  totalDeductions?: number;
  isAutoGenerated?: boolean;
  autoEntryType?: string;
  parentTransactionId?: string;
  isLocked?: boolean;
  editHistory?: EditHistoryRecord[];
  payments?: PaymentRecord[];
  timestamp: Timestamp;
  createdAt: Timestamp;
  updatedAt: Timestamp;
}

export interface CustomLedger {
  id: string;
  name: string;
  nameMr?: string;
  type: LedgerType | 'income' | 'expense' | 'both';
  partyType?: 'merchant' | 'labor_gang' | 'transporter' | 'dairy' | 'farmer' | 'other' | string;
  phone?: string;
  address?: string;
  notes?: string;
  description?: string;
  createdAt: Timestamp;
  updatedAt?: Timestamp;
}

