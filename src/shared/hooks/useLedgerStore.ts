import { create } from 'zustand';
import {
  collection,
  doc,
  getDocs,
  addDoc,
  updateDoc,
  deleteDoc,
  query,
  orderBy,
  Timestamp,
  writeBatch,
} from 'firebase/firestore';
import { db } from '../services/firebase';
import { Transaction, CustomLedger, PaymentRecord } from '../types/ledger';
import { useAuthStore } from './useAuthStore';
import { logger } from '../services/logger';

interface LedgerStore {
  transactions: Transaction[];
  customLedgers: CustomLedger[];
  isLoading: boolean;

  fetchTransactions: () => Promise<void>;
  createTransaction: (txn: Partial<Transaction>) => Promise<string>;
  updateTransaction: (id: string, updates: Partial<Transaction>) => Promise<void>;
  deleteTransaction: (id: string) => Promise<void>;
  postIncomeTransaction: (data: Partial<Transaction>) => Promise<void>;
  postExpenseTransaction: (data: Partial<Transaction>) => Promise<void>;
  recordCreditPayment: (txnId: string, payment: Omit<PaymentRecord, 'id' | 'createdAt'>) => Promise<void>;
  recordLoanEmiPayment: (txnId: string, payment: Omit<PaymentRecord, 'id' | 'createdAt'>) => Promise<void>;
  fetchCustomLedgers: () => Promise<void>;
  createCustomLedger: (ledger: Partial<CustomLedger>) => Promise<void>;
  deleteCustomLedger: (id: string) => Promise<void>;
  seedDefaultLedgers: () => Promise<void>;
}

const DEFAULT_LEDGERS: Partial<CustomLedger>[] = [
  { name: 'Cash Book', nameMr: 'रोख वही', type: 'both' },
  { name: 'Bank Book', nameMr: 'बँक वही', type: 'both' },
  { name: 'Party Ledger', nameMr: 'पार्टी खातेवही', type: 'both' },
  { name: 'Crop Expense', nameMr: 'पीक खर्च', type: 'expense' },
  { name: 'Dairy Ledger', nameMr: 'डेअरी खातेवही', type: 'both' },
  { name: 'Personal Expense', nameMr: 'वैयक्तिक खर्च', type: 'expense' },
  { name: 'Loan Ledger', nameMr: 'कर्ज खातेवही', type: 'both' },
];

function getUserMobile(): string {
  const user = useAuthStore.getState().user;
  if (!user) throw new Error('User not authenticated');
  return user.mobileNumber;
}

function getLedgerRef() {
  return collection(db, 'users', getUserMobile(), 'ledger');
}

function getCustomLedgerRef() {
  return collection(db, 'users', getUserMobile(), 'custom_ledgers');
}

export const useLedgerStore = create<LedgerStore>((set, get) => ({
  transactions: [],
  customLedgers: [],
  isLoading: false,

  fetchTransactions: async () => {
    set({ isLoading: true });
    try {
      const snap = await getDocs(getLedgerRef());
      const txns = snap.docs.map((d) => ({ id: d.id, ...d.data() } as Transaction));

      const userMobile = getUserMobile();
      try {
        const txSnap = await getDocs(collection(db, 'users', userMobile, 'transactions'));
        txSnap.docs.forEach((d) => {
          const data = d.data();
          if (!txns.some((t) => t.id === d.id)) {
            txns.push({
              id: d.id,
              type: 'income',
              ledgerType: 'agriculture',
              category: data.crop || 'Crop Sale',
              amount: Number(data.amount) || 0,
              date: data.timestamp ? data.timestamp.split('T')[0] : new Date().toISOString().split('T')[0],
              partyName: data.farmer || undefined,
              paymentMode: 'cash',
              timestamp: data.timestamp || new Date().toISOString(),
            } as Transaction);
          }
        });
      } catch {}

      txns.sort((a: any, b: any) => {
        const tA = new Date(a.date || a.timestamp || a.createdAt?.toDate?.() || 0).getTime();
        const tB = new Date(b.date || b.timestamp || b.createdAt?.toDate?.() || 0).getTime();
        return tB - tA;
      });

      set({ transactions: txns, isLoading: false });
    } catch (err) {
      logger.error('fetchTransactions error:', err);
      set({ isLoading: false });
    }
  },

  createTransaction: async (txn: Partial<Transaction>) => {
    const now = Timestamp.now();
    const data = {
      ...txn,
      timestamp: now,
      createdAt: now,
      updatedAt: now,
    };
    const docRef = await addDoc(getLedgerRef(), data);
    const newTxn = { id: docRef.id, ...data } as Transaction;
    set((s) => ({ transactions: [newTxn, ...s.transactions] }));
    return docRef.id;
  },

  updateTransaction: async (id: string, updates: Partial<Transaction>) => {
    const txn = get().transactions.find((t) => t.id === id);
    if (!txn) return;
    if (txn.isAutoGenerated) {
      logger.warn('Cannot edit auto-generated entry');
      return;
    }
    if (txn.isLocked) {
      logger.warn('Cannot edit locked entry');
      return;
    }
    const editRecord = {
      editedAt: new Date().toISOString(),
      editedFields: Object.keys(updates),
      previousValues: Object.fromEntries(
        Object.keys(updates).map((k) => [k, (txn as any)[k]])
      ),
    };
    const updateData = {
      ...updates,
      updatedAt: Timestamp.now(),
      editHistory: [...(txn.editHistory || []), editRecord],
    };
    await updateDoc(doc(getLedgerRef(), id), updateData);
    set((s) => ({
      transactions: s.transactions.map((t) =>
        t.id === id ? { ...t, ...updateData } as Transaction : t
      ),
    }));
  },

  deleteTransaction: async (id: string) => {
    const txn = get().transactions.find((t) => t.id === id);
    if (!txn) return;
    if (txn.isAutoGenerated) {
      logger.warn('Cannot delete auto-generated entry');
      return;
    }
    if (txn.isLocked) {
      logger.warn('Cannot delete locked entry');
      return;
    }
    // Cascade delete: remove child auto-generated entries
    const children = get().transactions.filter(
      (t) => t.parentTransactionId === id
    );
    const batch = writeBatch(db);
    batch.delete(doc(getLedgerRef(), id));
    children.forEach((c) => batch.delete(doc(getLedgerRef(), c.id)));
    await batch.commit();

    const deletedIds = new Set([id, ...children.map((c) => c.id)]);
    set((s) => ({
      transactions: s.transactions.filter((t) => !deletedIds.has(t.id)),
    }));
  },

  postIncomeTransaction: async (data: Partial<Transaction>) => {
    const txnId = await get().createTransaction({
      ...data,
      type: 'income',
    });

    // Auto-post deductions as separate expense entries for crop sales
    if (data.incomeCategory === 'crop_sale' && data.cropSaleDetails) {
      const details = data.cropSaleDetails;
      const deductions = [
        { name: 'Hamali', amount: details.hamaliDeduction, category: 'Hamali' },
        { name: 'Transport', amount: details.transportDeduction, category: 'Transport' },
        { name: 'Other', amount: details.otherDeduction, category: 'Other Agri' },
      ];

      for (const ded of deductions) {
        if (ded.amount && ded.amount > 0) {
          await get().createTransaction({
            type: 'expense',
            ledgerType: 'agriculture',
            category: ded.category,
            amount: ded.amount,
            date: data.date,
            paymentMode: 'cash',
            partyName: data.partyName,
            plotId: data.plotId,
            plotName: data.plotName,
            cropId: data.cropId,
            cropName: data.cropName,
            cropSeason: data.cropSeason,
            isAutoGenerated: true,
            autoEntryType: `crop_sale_${ded.name.toLowerCase()}`,
            parentTransactionId: txnId,
            isLocked: true,
          });
        }
      }
    }

    // Loan: net received = sanction - processing fee
    if (data.incomeCategory === 'loan' && data.loanDetails) {
      if (data.loanDetails.processingFee > 0) {
        await get().createTransaction({
          type: 'expense',
          ledgerType: 'personal',
          category: 'Loan Processing Fee',
          amount: data.loanDetails.processingFee,
          date: data.date,
          paymentMode: data.paymentMode || 'bank',
          isAutoGenerated: true,
          autoEntryType: 'loan_processing_fee',
          parentTransactionId: txnId,
          isLocked: true,
        });
      }
    }
  },

  postExpenseTransaction: async (data: Partial<Transaction>) => {
    await get().createTransaction({
      ...data,
      type: 'expense',
    });

    // Credit mode: auto-set due date (30 days) and pending amount
    if (data.paymentMode === 'credit') {
      const dueDate = new Date();
      dueDate.setDate(dueDate.getDate() + 30);
      const txns = get().transactions;
      const latest = txns[0];
      if (latest) {
        await get().updateTransaction(latest.id, {
          dueDate: dueDate.toISOString().split('T')[0],
          pendingAmount: data.amount,
          payments: [],
        });
      }
    }
  },

  recordCreditPayment: async (txnId: string, payment) => {
    const txn = get().transactions.find((t) => t.id === txnId);
    if (!txn) return;
    const paymentRecord: PaymentRecord = {
      ...payment,
      id: Date.now().toString(),
      createdAt: new Date().toISOString(),
    };
    const payments = [...(txn.payments || []), paymentRecord];
    const totalPaid = payments.reduce((sum, p) => sum + p.amount, 0);
    const pendingAmount = Math.max(0, txn.amount - totalPaid);
    await get().updateTransaction(txnId, { payments, pendingAmount } as any);
  },

  recordLoanEmiPayment: async (txnId: string, payment) => {
    await get().recordCreditPayment(txnId, payment);
  },

  fetchCustomLedgers: async () => {
    try {
      const snap = await getDocs(getCustomLedgerRef());
      const ledgers = snap.docs.map((d) => ({ id: d.id, ...d.data() } as CustomLedger));
      set({ customLedgers: ledgers });
      if (ledgers.length === 0) {
        await get().seedDefaultLedgers();
      }
    } catch (err) {
      logger.error('fetchCustomLedgers error:', err);
    }
  },

  createCustomLedger: async (ledger: Partial<CustomLedger>) => {
    const now = Timestamp.now();
    const data = { ...ledger, createdAt: now, updatedAt: now };
    const docRef = await addDoc(getCustomLedgerRef(), data);
    set((s) => ({
      customLedgers: [...s.customLedgers, { id: docRef.id, ...data } as CustomLedger],
    }));
  },

  deleteCustomLedger: async (id: string) => {
    await deleteDoc(doc(getCustomLedgerRef(), id));
    set((s) => ({
      customLedgers: s.customLedgers.filter((l) => l.id !== id),
    }));
  },

  seedDefaultLedgers: async () => {
    const now = Timestamp.now();
    for (const ledger of DEFAULT_LEDGERS) {
      await get().createCustomLedger({ ...ledger, createdAt: now, updatedAt: now } as any);
    }
  },
}));
