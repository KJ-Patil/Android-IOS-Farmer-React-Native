import React, { useState, useMemo } from 'react';
import {
  View,
  Text,
  StyleSheet,
  FlatList,
  TouchableOpacity,
  TextInput,
  ScrollView,
  Alert,
  Platform,
} from 'react-native';
import { useTranslation } from 'react-i18next';
import { useTheme } from '../../../app/providers/ThemeProvider';
import { useLedgerStore } from '../../../shared/hooks/useLedgerStore';
import { Card } from '../../../components/ui/Card';
import { Badge } from '../../../components/ui/Badge';
import { useLocalizedFormat } from '../../../shared/hooks/useLocalizedFormat';
import { tCategory, tPaymentMode } from '../../../shared/utils/helpers';
import {
  TrendingDown,
  Sprout,
  Milk,
  Home,
  Search,
  Trash2,
  X,
  IndianRupee,
} from 'lucide-react-native';
import { fontSizes } from '../../../shared/utils/typography';

interface ExpenseRegisterViewProps {
  onOpenMoneyOutModal?: () => void;
}

export function ExpenseRegisterView({ onOpenMoneyOutModal }: ExpenseRegisterViewProps) {
  const { t } = useTranslation();
  const { colors } = useTheme();
  const { transactions, deleteTransaction } = useLedgerStore();
  const { fmtCurrency, toNative, fmtDMY } = useLocalizedFormat();

  const [searchQuery, setSearchQuery] = useState('');
  const [filterCategory, setFilterCategory] = useState<string>('all');

  const expenseTransactions = useMemo(() => {
    return transactions.filter((tx) => tx.type === 'expense' && !tx.isAutoGenerated);
  }, [transactions]);

  const todayStr = new Date().toISOString().split('T')[0];
  const currentMonthKey = todayStr.substring(0, 7);

  const todayExpense = expenseTransactions
    .filter((tx) => (tx.date || '').startsWith(todayStr))
    .reduce((s, tx) => s + (tx.amount || 0), 0);

  const monthExpense = expenseTransactions
    .filter((tx) => (tx.date || '').startsWith(currentMonthKey))
    .reduce((s, tx) => s + (tx.amount || 0), 0);

  const totalExpense = expenseTransactions.reduce((s, tx) => s + (tx.amount || 0), 0);

  const filteredRegister = useMemo(() => {
    return expenseTransactions.filter((tx) => {
      const matchesCat =
        filterCategory === 'all' ||
        tx.ledgerType === filterCategory;

      const q = searchQuery.toLowerCase().trim();
      const matchesSearch =
        !q ||
        (tx.category || '').toLowerCase().includes(q) ||
        (tx.partyName || '').toLowerCase().includes(q) ||
        (tx.notes || '').toLowerCase().includes(q) ||
        (tx.billNumber || '').toLowerCase().includes(q) ||
        (tx.plotName || '').toLowerCase().includes(q);

      return matchesCat && matchesSearch;
    });
  }, [expenseTransactions, filterCategory, searchQuery]);

  const handleDelete = (txId: string) => {
    if (Platform.OS === 'web') {
      if (window.confirm(t('confirmDeleteTransaction'))) {
        deleteTransaction(txId).catch((err: any) => alert(err.message));
      }
      return;
    }
    Alert.alert(
      t('deleteTransaction'),
      t('confirmDeleteTransaction'),
      [
        { text: t('cancel'), style: 'cancel' },
        {
          text: t('delete'),
          style: 'destructive',
          onPress: async () => {
            try {
              await deleteTransaction(txId);
            } catch (err: any) {
              Alert.alert(t('error'), err.message);
            }
          },
        },
      ]
    );
  };

  const fmt = (v: number) => fmtCurrency(Math.round(v));

  return (
    <View style={{ flex: 1 }}>
      <FlatList
        data={filteredRegister}
        keyExtractor={(tx) => tx.id}
        contentContainerStyle={{ paddingHorizontal: 16, paddingBottom: 100 }}
        ListHeaderComponent={
          <View style={{ paddingTop: 8 }}>
            <Card style={{ borderRadius: 16 }} padding={16}>
              <View style={{ flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between' }}>
                <View style={{ flex: 1 }}>
                  <View style={{ flexDirection: 'row', alignItems: 'center', gap: 8 }}>
                    <View style={[styles.summaryIcon, { backgroundColor: '#FEE2E2' }]}>
                      <IndianRupee color="#DC2626" size={20} />
                    </View>
                    <Text style={{ color: colors.foreground, fontSize: fontSizes.md, fontWeight: '700' }}>
                      {t('expenseRegisterTitle')}
                    </Text>
                  </View>
                </View>

                {onOpenMoneyOutModal && (
                  <TouchableOpacity
                    onPress={onOpenMoneyOutModal}
                    style={styles.addButton}
                    activeOpacity={0.8}
                  >
                    <Text style={{ color: '#FFFFFF', fontWeight: '800', fontSize: fontSizes.base }}>+ {t('add')}</Text>
                  </TouchableOpacity>
                )}
              </View>

              <View style={[styles.kpiTable, { backgroundColor: colors.card, borderColor: colors.border }]}>
                <View style={styles.kpiCol}>
                  <Text style={[styles.kpiLabel, { color: colors.mutedFg }]}>{t('todaysExpense')}</Text>
                  <Text style={[styles.kpiValue, { color: '#DC2626' }]} numberOfLines={1}>
                    {fmt(todayExpense)}
                  </Text>
                </View>
                <View style={[styles.kpiDivider, { backgroundColor: colors.border }]} />
                <View style={styles.kpiCol}>
                  <Text style={[styles.kpiLabel, { color: colors.mutedFg }]}>{t('thisMonth')}</Text>
                  <Text style={[styles.kpiValue, { color: colors.foreground }]} numberOfLines={1}>
                    {fmt(monthExpense)}
                  </Text>
                </View>
                <View style={[styles.kpiDivider, { backgroundColor: colors.border }]} />
                <View style={styles.kpiCol}>
                  <Text style={[styles.kpiLabel, { color: colors.mutedFg }]}>{t('totalMoneyOut')}</Text>
                  <Text style={[styles.kpiValue, { color: '#DC2626' }]} numberOfLines={1}>
                    {fmt(totalExpense)}
                  </Text>
                </View>
              </View>
            </Card>

            <View style={{ marginTop: 16, marginBottom: 8 }}>
              <View style={[styles.searchBox, { borderColor: colors.border, backgroundColor: colors.card }]}>
                <Search color={colors.mutedFg} size={16} />
                <TextInput
                  placeholder={t('searchExpensePlaceholder')}
                  placeholderTextColor={colors.mutedFg}
                  value={searchQuery}
                  onChangeText={setSearchQuery}
                  style={[styles.searchInput, { color: colors.foreground }]}
                />
                {searchQuery.length > 0 && (
                  <TouchableOpacity onPress={() => setSearchQuery('')}>
                    <X color={colors.mutedFg} size={16} />
                  </TouchableOpacity>
                )}
              </View>

              <ScrollView horizontal showsHorizontalScrollIndicator={false} style={{ marginTop: 10 }}>
                {[
                  { key: 'all', label: t('all') },
                  { key: 'agriculture', label: t('agricultureExpense') },
                  { key: 'dairy', label: t('dairyExpense') },
                  { key: 'personal', label: t('personalExpense') },
                ].map((cat) => (
                  <TouchableOpacity
                    key={cat.key}
                    onPress={() => setFilterCategory(cat.key)}
                    style={[
                      styles.filterChip,
                      {
                        backgroundColor: filterCategory === cat.key ? colors.destructive + '15' : colors.card,
                        borderColor: filterCategory === cat.key ? colors.destructive : colors.border,
                      },
                    ]}
                  >
                    <Text
                      style={{
                        color: filterCategory === cat.key ? colors.destructive : colors.mutedFg,
                        fontWeight: '700',
                        fontSize: fontSizes.sm,
                      }}
                    >
                      {cat.label}
                    </Text>
                  </TouchableOpacity>
                ))}
              </ScrollView>
            </View>
          </View>
        }
        ListEmptyComponent={
          <View style={{ paddingVertical: 40, alignItems: 'center' }}>
            <TrendingDown color={colors.mutedFg} size={36} />
            <Text style={{ color: colors.mutedFg, textAlign: 'center', marginTop: 10, fontSize: fontSizes.sm, fontWeight: '600' }}>
              {t('noExpenseFound')}
            </Text>
          </View>
        }
        renderItem={({ item: tx }) => (
          <Card style={{ marginTop: 8 }} padding={12}>
            <View style={styles.txnRow}>
              <View style={[styles.iconCircle, { backgroundColor: colors.destructive + '15' }]}>
                {tx.ledgerType === 'agriculture' ? (
                  <Sprout color={colors.primary} size={18} />
                ) : tx.ledgerType === 'dairy' ? (
                  <Milk color="#6366F1" size={18} />
                ) : (
                  <Home color="#8B5CF6" size={18} />
                )}
              </View>

              <View style={{ flex: 1, marginLeft: 10 }}>
                <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6, flexWrap: 'wrap' }}>
                  <Text style={{ color: colors.foreground, fontSize: fontSizes.sm, fontWeight: '700' }}>
                    {tCategory(tx.category, t)}
                  </Text>
                  <Badge
                    text={tPaymentMode(tx.paymentMode, t)}
                    variant={tx.paymentMode === 'cash' ? 'default' : 'info'}
                  />
                  {tx.billNumber && <Badge text={`#${tx.billNumber}`} variant="default" />}
                </View>

                <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6, marginTop: 4, flexWrap: 'wrap' }}>
                  <Text style={{ color: colors.mutedFg, fontSize: fontSizes.sm }}>{fmtDMY(tx.date)}</Text>
                  {tx.partyName && (
                    <Text style={{ color: colors.foreground, fontSize: fontSizes.sm, fontWeight: '600' }}>
                      • {tx.partyName}
                    </Text>
                  )}
                  {tx.plotName && (
                    <Text style={{ color: colors.primary, fontSize: fontSizes.sm }}>• {tx.plotName}</Text>
                  )}
                </View>

                {tx.notes && (
                  <Text style={{ color: colors.mutedFg, fontSize: fontSizes.sm, fontStyle: 'italic', marginTop: 2 }}>
                    {tx.notes}
                  </Text>
                )}
              </View>

              <View style={{ alignItems: 'flex-end', marginLeft: 8 }}>
                <Text style={{ color: colors.destructive, fontSize: fontSizes.base, fontWeight: '700' }}>
                  -{fmt(tx.amount)}
                </Text>

                <TouchableOpacity
                  onPress={() => handleDelete(tx.id)}
                  style={{ marginTop: 6, padding: 4 }}
                  hitSlop={{ top: 8, bottom: 8, left: 8, right: 8 }}
                >
                  <Trash2 color={colors.mutedFg} size={14} />
                </TouchableOpacity>
              </View>
            </View>
          </Card>
        )}
      />
    </View>
  );
}

const styles = StyleSheet.create({
  summaryIcon: { width: 36, height: 36, borderRadius: 10, alignItems: 'center', justifyContent: 'center' },
  addButton: { paddingHorizontal: 18, height: 44, borderRadius: 14, backgroundColor: '#DC2626', alignItems: 'center', justifyContent: 'center', elevation: 4, shadowColor: '#DC2626', shadowOffset: { width: 0, height: 4 }, shadowOpacity: 0.3, shadowRadius: 8 },
  searchBox: { flexDirection: 'row', alignItems: 'center', borderWidth: 1, borderRadius: 12, paddingHorizontal: 10, height: 40 },
  searchInput: { flex: 1, marginLeft: 8, fontSize: fontSizes.sm, height: '100%' },
  filterChip: { paddingHorizontal: 12, paddingVertical: 6, borderRadius: 20, borderWidth: 1, marginRight: 8 },
  txnRow: { flexDirection: 'row', alignItems: 'center' },
  iconCircle: { width: 38, height: 38, borderRadius: 12, alignItems: 'center', justifyContent: 'center' },
  kpiTable: { flexDirection: 'row', marginTop: 14, borderRadius: 12, borderWidth: 1, padding: 14, shadowColor: '#000', shadowOffset: { width: 0, height: 2 }, shadowOpacity: 0.08, shadowRadius: 6, elevation: 3 },
  kpiCol: { flex: 1, alignItems: 'center', justifyContent: 'space-between' },
  kpiDivider: { width: 1, alignSelf: 'stretch', marginVertical: 2 },
  kpiLabel: { fontSize: fontSizes.xs, fontWeight: '600', textTransform: 'uppercase', letterSpacing: 0.3, textAlign: 'center' },
  kpiValue: { fontSize: fontSizes.md, fontWeight: '800', marginTop: 4, textAlign: 'center' },
});
