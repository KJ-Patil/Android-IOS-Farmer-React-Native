import React, { useState, useMemo } from 'react';
import {
  View,
  Text,
  StyleSheet,
  FlatList,
  TouchableOpacity,
  TextInput,
  ScrollView,
  Modal,
  Alert,
} from 'react-native';
import { useTranslation } from 'react-i18next';
import { useTheme } from '../../../app/providers/ThemeProvider';
import { useLedgerStore } from '../../../shared/hooks/useLedgerStore';
import { Card } from '../../../components/ui/Card';
import { Badge } from '../../../components/ui/Badge';
import { Button } from '../../../components/ui/Button';
import { Input } from '../../../components/ui/Input';
import { DatePickerInput } from '../../../components/ui/DatePickerInput';
import type { Transaction, PaymentMode } from '../../../shared/types/ledger';
import { useLocalizedFormat } from '../../../shared/hooks/useLocalizedFormat';
import { tCategory, tPaymentMode } from '../../../shared/utils/helpers';
import {
  TrendingUp,
  Sprout,
  Milk,
  Landmark,
  Briefcase,
  Calendar,
  Clock,
  Plus,
  Search,
  Trash2,
  X,
  CreditCard,
  IndianRupee,
} from 'lucide-react-native';

interface IncomeRegisterViewProps {
  onOpenMoneyInModal?: () => void;
}

export function IncomeRegisterView({ onOpenMoneyInModal }: IncomeRegisterViewProps) {
  const { t } = useTranslation();
  const { colors } = useTheme();
  const { transactions, deleteTransaction, recordLoanEmiPayment } = useLedgerStore();
  const { fmtCurrency, toNative, fmtDMY } = useLocalizedFormat();

  const [searchQuery, setSearchQuery] = useState('');
  const [filterCategory, setFilterCategory] = useState<string>('all');

  // EMI Modal State
  const [selectedLoanTx, setSelectedLoanTx] = useState<Transaction | null>(null);
  const [emiAmount, setEmiAmount] = useState('');
  const [emiDate, setEmiDate] = useState(new Date().toISOString().split('T')[0]);
  const [emiMode, setEmiMode] = useState<PaymentMode>('bank');
  const [emiNotes, setEmiNotes] = useState('');
  const [emiLoading, setEmiLoading] = useState(false);

  // Income transactions (excluding auto-generated expense splits)
  const incomeTransactions = useMemo(() => {
    return transactions.filter((tx) => tx.type === 'income' && !tx.isAutoGenerated);
  }, [transactions]);

  const todayStr = new Date().toISOString().split('T')[0];
  const currentMonthKey = todayStr.substring(0, 7);
  const currentYearKey = todayStr.substring(0, 4);

  // High-level KPIs
  const todayIncome = incomeTransactions
    .filter((tx) => (tx.date || '').startsWith(todayStr))
    .reduce((s, tx) => s + (tx.amount || 0), 0);

  const monthIncome = incomeTransactions
    .filter((tx) => (tx.date || '').startsWith(currentMonthKey))
    .reduce((s, tx) => s + (tx.amount || 0), 0);

  const yearIncome = incomeTransactions
    .filter((tx) => (tx.date || '').startsWith(currentYearKey))
    .reduce((s, tx) => s + (tx.amount || 0), 0);

  const totalNetIncome = incomeTransactions.reduce((s, tx) => s + (tx.amount || 0), 0);
  const totalGrossIncome = incomeTransactions.reduce(
    (s, tx) => s + (tx.grossAmount || tx.amount || 0),
    0
  );

  const totalFarmExpenses = transactions
    .filter((tx) => tx.type === 'expense')
    .reduce((s, tx) => s + (tx.amount || 0), 0);
  const netFarmProfit = totalGrossIncome - totalFarmExpenses;

  // Category breakdown
  const cropSales = incomeTransactions.filter(
    (tx) => tx.incomeCategory === 'crop_sale' || tx.category === 'crop_sale' || tx.cropName
  );
  const dairyIncomes = incomeTransactions.filter(
    (tx) =>
      tx.incomeCategory === 'dairy' ||
      (tx.category && (tx.category.includes('दूध') || tx.category.toLowerCase().includes('dairy')))
  );
  const loanIncomes = incomeTransactions.filter(
    (tx) =>
      tx.incomeCategory === 'loan' ||
      (tx.category && (tx.category.includes('कर्ज') || tx.category.toLowerCase().includes('loan')))
  );
  const otherIncomes = incomeTransactions.filter(
    (tx) =>
      tx.incomeCategory === 'other' ||
      (!tx.incomeCategory && tx.category !== 'crop_sale' && !dairyIncomes.includes(tx) && !loanIncomes.includes(tx))
  );

  const totalCropSaleGross = cropSales.reduce((s, tx) => s + (tx.grossAmount || tx.amount || 0), 0);
  const totalCropSaleNet = cropSales.reduce((s, tx) => s + (tx.amount || 0), 0);
  const totalDairyIncome = dairyIncomes.reduce((s, tx) => s + (tx.amount || 0), 0);
  const totalLoanReceived = loanIncomes.reduce((s, tx) => s + (tx.amount || 0), 0);
  const totalOtherIncome = otherIncomes.reduce((s, tx) => s + (tx.amount || 0), 0);

  // Active Loans & Liabilities Tracker
  const activeLoans = useMemo(() => {
    return transactions.filter(
      (tx) =>
        tx.autoEntryType === 'loan_outstanding' ||
        (tx.loanDetails && tx.type === 'income') ||
        (tx.incomeCategory === 'loan' && (tx.pendingAmount === undefined || tx.pendingAmount > 0))
    );
  }, [transactions]);

  // Filtered transactions
  const filteredRegister = useMemo(() => {
    return incomeTransactions.filter((tx) => {
      const matchesCat =
        filterCategory === 'all' ||
        tx.incomeCategory === filterCategory ||
        (filterCategory === 'crop_sale' && (tx.category === 'crop_sale' || tx.cropName)) ||
        (filterCategory === 'dairy' && dairyIncomes.includes(tx)) ||
        (filterCategory === 'loan' && loanIncomes.includes(tx)) ||
        (filterCategory === 'other' && otherIncomes.includes(tx));

      const q = searchQuery.toLowerCase().trim();
      const matchesSearch =
        !q ||
        (tx.category || '').toLowerCase().includes(q) ||
        (tx.cropName || '').toLowerCase().includes(q) ||
        (tx.partyName || '').toLowerCase().includes(q) ||
        (tx.notes || '').toLowerCase().includes(q) ||
        (tx.billNumber || '').toLowerCase().includes(q);

      return matchesCat && matchesSearch;
    });
  }, [incomeTransactions, filterCategory, searchQuery, dairyIncomes, loanIncomes, otherIncomes]);

  const handleEmiSubmit = async () => {
    if (!selectedLoanTx || !emiAmount || Number(emiAmount) <= 0) {
      Alert.alert(t('required'), t('enterValidEmiAmount'));
      return;
    }
    setEmiLoading(true);
    try {
      await recordLoanEmiPayment(selectedLoanTx.id, {
        amount: Number(emiAmount),
        date: emiDate,
        paymentMode: emiMode,
        notes: emiNotes || `${selectedLoanTx.partyName || t('bank')} - ${t('payLoanEmi')}`,
      });
      setSelectedLoanTx(null);
      setEmiAmount('');
      setEmiNotes('');
      Alert.alert(t('success'), t('loanEmiRecordedSuccessfully'));
    } catch (err: any) {
      Alert.alert(t('error'), err.message);
    } finally {
      setEmiLoading(false);
    }
  };

  const handleDelete = (txId: string) => {
    Alert.alert(
      t('deleteTransaction'),
      t('confirmDeleteTransaction'),
      [
        { text: t('cancel'), style: 'cancel' },
        {
          text: t('delete'),
          style: 'destructive',
          onPress: async () => {
            try {
              await deleteTransaction(txId);
            } catch (err: any) {
              Alert.alert(t('error'), err.message);
            }
          },
        },
      ]
    );
  };

  const fmt = (v: number) => fmtCurrency(Math.round(v));

  return (
    <View style={{ flex: 1 }}>
      <FlatList
        data={filteredRegister}
        keyExtractor={(tx) => tx.id}
        contentContainerStyle={{ paddingHorizontal: 16, paddingBottom: 100 }}
        ListHeaderComponent={
          <View style={{ paddingTop: 8 }}>
            {/* Summary Card */}
            <Card style={{ borderRadius: 16 }} padding={16}>
              <View style={{ flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between' }}>
                <View style={{ flex: 1 }}>
                  <View style={{ flexDirection: 'row', alignItems: 'center', gap: 8 }}>
                    <View style={[styles.summaryIcon, { backgroundColor: '#DCFCE7' }]}>
                      <IndianRupee color="#16A34A" size={20} />
                    </View>
                    <Text style={[styles.mainTitle, { color: colors.foreground }]}>
                      {t('incomeRegisterTitle')}
                    </Text>
                  </View>
                  <Text style={[styles.totalAmount, { color: colors.foreground }]}>
                    {fmt(totalNetIncome)}
                  </Text>
                  <View style={{ flexDirection: 'row', gap: 16, marginTop: 6 }}>
                    <View>
                      <Text style={{ color: colors.mutedFg, fontSize: 12 }}>{t('thisMonth')}</Text>
                      <Text style={{ color: colors.foreground, fontSize: 14, fontWeight: '700' }}>{fmt(monthIncome)}</Text>
                    </View>
                    <View>
                      <Text style={{ color: colors.mutedFg, fontSize: 12 }}>{t('todaysIncome')}</Text>
                      <Text style={{ color: '#16A34A', fontSize: 14, fontWeight: '700' }}>{fmt(todayIncome)}</Text>
                    </View>
                  </View>
                </View>

                {onOpenMoneyInModal && (
                  <TouchableOpacity
                    onPress={onOpenMoneyInModal}
                    style={styles.addButton}
                    activeOpacity={0.8}
                  >
                    <Plus color="#FFFFFF" size={28} strokeWidth={2.5} />
                  </TouchableOpacity>
                )}
              </View>
            </Card>

            {/* Active Loans & EMI Reminders Section */}
            {activeLoans.length > 0 && (
              <Card
                style={{
                  marginTop: 14,
                  borderColor: colors.warning + '40',
                  backgroundColor: colors.warning + '08',
                }}
                padding={14}
              >
                <View style={{ flexDirection: 'row', justifyContent: 'space-between', alignItems: 'center', marginBottom: 10 }}>
                  <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6 }}>
                    <Clock color={colors.warning} size={16} />
                    <Text style={{ color: colors.foreground, fontWeight: '700', fontSize: 13 }}>
                      {t('activeLoansAndEmi')}
                    </Text>
                  </View>
                  <Badge text={`${toNative(activeLoans.length)} ${t('loansCount')}`} variant="warning" />
                </View>

                {activeLoans.map((loan) => {
                  const pending = loan.pendingAmount !== undefined ? loan.pendingAmount : loan.amount;
                  const isOverdue = loan.dueDate && loan.dueDate < todayStr && pending > 0;

                  return (
                    <View
                      key={loan.id}
                      style={[
                        styles.loanItemCard,
                        { borderColor: colors.border, backgroundColor: colors.card },
                      ]}
                    >
                      <View style={{ flexDirection: 'row', justifyContent: 'space-between', alignItems: 'flex-start' }}>
                        <View style={{ flex: 1 }}>
                          <Text style={{ color: colors.foreground, fontWeight: '700', fontSize: 13 }}>
                            {loan.partyName || tCategory(loan.category, t)}
                          </Text>
                          <Text style={{ color: colors.mutedFg, fontSize: 13, marginTop: 2 }}>
                            {loan.loanDetails?.loanType || t('bankLoan')}
                            {loan.loanDetails?.interestRate ? ` • ${toNative(loan.loanDetails.interestRate)}%` : ''}
                          </Text>
                        </View>
                        <View style={{ alignItems: 'flex-end' }}>
                          <Text style={{ color: colors.mutedFg, fontSize: 13 }}>
                            {t('outstanding')}
                          </Text>
                          <Text style={{ color: colors.destructive, fontWeight: '700', fontSize: 14 }}>
                            {fmt(pending)}
                          </Text>
                        </View>
                      </View>

                      <View
                        style={{
                          flexDirection: 'row',
                          justifyContent: 'space-between',
                          alignItems: 'center',
                          marginTop: 8,
                          paddingTop: 8,
                          borderTopWidth: StyleSheet.hairlineWidth,
                          borderTopColor: colors.border,
                        }}
                      >
                        <View style={{ flexDirection: 'row', alignItems: 'center', gap: 4 }}>
                          <Calendar color={colors.mutedFg} size={12} />
                          <Text style={{ color: isOverdue ? colors.destructive : colors.mutedFg, fontSize: 13, fontWeight: '600' }}>
                            {fmtDMY(loan.dueDate || loan.loanDetails?.firstInstallmentDate) || '—'}
                          </Text>
                        </View>

                        <Button
                          title={t('payEmi')}
                          onPress={() => {
                            setSelectedLoanTx(loan);
                            setEmiAmount(String(Math.min(pending, 5000)));
                          }}
                          size="sm"
                          variant="secondary"
                        />
                      </View>
                    </View>
                  );
                })}
              </Card>
            )}

            {/* Filter Pills & Search Bar */}
            <View style={{ marginTop: 16, marginBottom: 8 }}>
              <View style={[styles.searchBox, { borderColor: colors.border, backgroundColor: colors.card }]}>
                <Search color={colors.mutedFg} size={16} />
                <TextInput
                  placeholder={t('searchIncomePlaceholder')}
                  placeholderTextColor={colors.mutedFg}
                  value={searchQuery}
                  onChangeText={setSearchQuery}
                  style={[styles.searchInput, { color: colors.foreground }]}
                />
                {searchQuery.length > 0 && (
                  <TouchableOpacity onPress={() => setSearchQuery('')}>
                    <X color={colors.mutedFg} size={16} />
                  </TouchableOpacity>
                )}
              </View>

              <ScrollView horizontal showsHorizontalScrollIndicator={false} style={{ marginTop: 10 }}>
                {[
                  { key: 'all', label: t('all') },
                  { key: 'crop_sale', label: t('cropSales') },
                  { key: 'dairy', label: t('dairyIncome') },
                  { key: 'loan', label: t('loans') },
                  { key: 'other', label: t('other') },
                ].map((cat) => (
                  <TouchableOpacity
                    key={cat.key}
                    onPress={() => setFilterCategory(cat.key)}
                    style={[
                      styles.filterChip,
                      {
                        backgroundColor: filterCategory === cat.key ? colors.primary + '15' : colors.card,
                        borderColor: filterCategory === cat.key ? colors.primary : colors.border,
                      },
                    ]}
                  >
                    <Text
                      style={{
                        color: filterCategory === cat.key ? colors.primary : colors.mutedFg,
                        fontWeight: '700',
                        fontSize: 12,
                      }}
                    >
                      {cat.label}
                    </Text>
                  </TouchableOpacity>
                ))}
              </ScrollView>
            </View>
          </View>
        }
        ListEmptyComponent={
          <View style={{ paddingVertical: 40, alignItems: 'center' }}>
            <TrendingUp color={colors.mutedFg} size={36} />
            <Text style={{ color: colors.mutedFg, textAlign: 'center', marginTop: 10, fontSize: 13, fontWeight: '600' }}>
              {t('noIncomeFound')}
            </Text>
          </View>
        }
        renderItem={({ item: tx }) => {
          const hasDeductions = (tx.totalDeductions || 0) > 0;
          const gross = tx.grossAmount || tx.amount;

          return (
            <Card style={{ marginTop: 8 }} padding={12}>
              <View style={styles.txnRow}>
                <View style={[styles.iconCircle, { backgroundColor: colors.primary + '15' }]}>
                  {tx.incomeCategory === 'dairy' ? (
                    <Milk color="#6366F1" size={18} />
                  ) : tx.incomeCategory === 'loan' ? (
                    <Landmark color={colors.warning} size={18} />
                  ) : tx.incomeCategory === 'other' ? (
                    <Briefcase color="#8B5CF6" size={18} />
                  ) : (
                    <Sprout color={colors.primary} size={18} />
                  )}
                </View>

                <View style={{ flex: 1, marginLeft: 10 }}>
                  <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6, flexWrap: 'wrap' }}>
                    <Text style={[styles.txnTitle, { color: colors.foreground }]}>
                      {tx.cropName ? `${t(tx.cropName)} ${t('sale')}` : tCategory(tx.category, t)}
                    </Text>
                    <Badge
                      text={tPaymentMode(tx.paymentMode, t)}
                      variant={tx.paymentMode === 'cash' ? 'default' : 'info'}
                    />
                    {tx.billNumber && <Badge text={`#${tx.billNumber}`} variant="default" />}
                  </View>

                  <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6, marginTop: 4, flexWrap: 'wrap' }}>
                    <Text style={{ color: colors.mutedFg, fontSize: 13 }}>{fmtDMY(tx.date)}</Text>
                    {tx.partyName && (
                      <Text style={{ color: colors.foreground, fontSize: 13, fontWeight: '600' }}>
                        • {tx.partyName}
                      </Text>
                    )}
                    {tx.plotName && (
                      <Text style={{ color: colors.primary, fontSize: 13 }}>• {tx.plotName}</Text>
                    )}
                  </View>

                  {tx.notes && (
                    <Text style={{ color: colors.mutedFg, fontSize: 13, fontStyle: 'italic', marginTop: 2 }}>
                      {tx.notes}
                    </Text>
                  )}
                </View>

                <View style={{ alignItems: 'flex-end', marginLeft: 8 }}>
                  <Text style={[styles.amountText, { color: colors.primary }]}>
                    +{fmt(tx.amount)}
                  </Text>
                  {hasDeductions && (
                    <Text style={{ color: colors.mutedFg, fontSize: 9 }}>
                      {t('gross')}: {fmt(gross)}
                    </Text>
                  )}

                  <TouchableOpacity
                    onPress={() => handleDelete(tx.id)}
                    style={{ marginTop: 6, padding: 4 }}
                    hitSlop={{ top: 8, bottom: 8, left: 8, right: 8 }}
                  >
                    <Trash2 color={colors.mutedFg} size={14} />
                  </TouchableOpacity>
                </View>
              </View>
            </Card>
          );
        }}
      />

      {/* Pay EMI Modal */}
      {selectedLoanTx && (
        <Modal visible={true} transparent animationType="fade" onRequestClose={() => setSelectedLoanTx(null)}>
          <View style={styles.modalOverlay}>
            <View style={[styles.modalCard, { backgroundColor: colors.background, borderColor: colors.border }]}>
              <View style={styles.modalHeader}>
                <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6 }}>
                  <CreditCard color={colors.warning} size={18} />
                  <Text style={[styles.modalTitle, { color: colors.foreground }]}>
                    {t('payLoanEmi')}
                  </Text>
                </View>
                <TouchableOpacity onPress={() => setSelectedLoanTx(null)}>
                  <X color={colors.foreground} size={20} />
                </TouchableOpacity>
              </View>

              <Text style={{ color: colors.mutedFg, fontSize: 12, marginBottom: 12 }}>
                {selectedLoanTx.partyName || tCategory(selectedLoanTx.category, t)} •{' '}
                {t('outstanding')}:{' '}
                <Text style={{ fontWeight: '700', color: colors.destructive }}>
                  {fmt(selectedLoanTx.pendingAmount ?? selectedLoanTx.amount)}
                </Text>
              </Text>

              <Input
                label={t('emiAmount')}
                value={emiAmount}
                onChangeText={(v) => setEmiAmount(v.replace(/[^0-9.]/g, ''))}
                keyboardType="decimal-pad"
                placeholder="5000"
              />

              <DatePickerInput
                label={t('paymentDate')}
                value={emiDate}
                onChange={setEmiDate}
              />

              <Text style={[styles.inputLabel, { color: colors.foreground }]}>
                {t('paymentMode')}
              </Text>
              <View style={styles.modeRow}>
                {(['bank', 'cash', 'upi'] as PaymentMode[]).map((mode) => (
                  <TouchableOpacity
                    key={mode}
                    onPress={() => setEmiMode(mode)}
                    style={[
                      styles.modeChip,
                      {
                        backgroundColor: emiMode === mode ? colors.primary + '15' : colors.card,
                        borderColor: emiMode === mode ? colors.primary : colors.border,
                      },
                    ]}
                  >
                    <Text
                      style={{
                        color: emiMode === mode ? colors.primary : colors.foreground,
                        fontWeight: '700',
                        fontSize: 12,
                      }}
                    >
                      {t(mode)}
                    </Text>
                  </TouchableOpacity>
                ))}
              </View>

              <Input
                label={t('notes')}
                value={emiNotes}
                onChangeText={setEmiNotes}
                placeholder={t('loanPaymentNotesPlaceholder')}
              />

              <View style={{ flexDirection: 'row', gap: 10, marginTop: 16 }}>
                <Button
                  title={t('cancel')}
                  variant="outline"
                  onPress={() => setSelectedLoanTx(null)}
                  style={{ flex: 1 }}
                />
                <Button
                  title={t('submitPayment')}
                  loading={emiLoading}
                  onPress={handleEmiSubmit}
                  style={{ flex: 1 }}
                />
              </View>
            </View>
          </View>
        </Modal>
      )}
    </View>
  );
}

const styles = StyleSheet.create({
  mainTitle: { fontSize: 15, fontWeight: '700' },
  summaryIcon: { width: 36, height: 36, borderRadius: 10, alignItems: 'center', justifyContent: 'center' },
  totalAmount: { fontSize: 28, fontWeight: '800', marginTop: 8, letterSpacing: -0.5 },
  addButton: { width: 56, height: 56, borderRadius: 16, backgroundColor: '#16A34A', alignItems: 'center', justifyContent: 'center', elevation: 4, shadowColor: '#16A34A', shadowOffset: { width: 0, height: 4 }, shadowOpacity: 0.3, shadowRadius: 8 },
  loanItemCard: { padding: 10, borderRadius: 12, borderWidth: 1, marginTop: 8 },
  searchBox: { flexDirection: 'row', alignItems: 'center', borderWidth: 1, borderRadius: 12, paddingHorizontal: 10, height: 40 },
  searchInput: { flex: 1, marginLeft: 8, fontSize: 13, height: '100%' },
  filterChip: { paddingHorizontal: 12, paddingVertical: 6, borderRadius: 20, borderWidth: 1, marginRight: 8 },
  txnRow: { flexDirection: 'row', alignItems: 'center' },
  iconCircle: { width: 38, height: 38, borderRadius: 12, alignItems: 'center', justifyContent: 'center' },
  txnTitle: { fontSize: 13, fontWeight: '700' },
  amountText: { fontSize: 15, fontWeight: '800' },
  modalOverlay: { flex: 1, backgroundColor: 'rgba(0,0,0,0.6)', justifyContent: 'center', padding: 20 },
  modalCard: { borderRadius: 16, borderWidth: 1, padding: 18 },
  modalHeader: { flexDirection: 'row', justifyContent: 'space-between', alignItems: 'center', marginBottom: 6 },
  modalTitle: { fontSize: 16, fontWeight: '700' },
  inputLabel: { fontSize: 12, fontWeight: '600', marginBottom: 6, marginTop: 4 },
  modeRow: { flexDirection: 'row', gap: 8, marginBottom: 12 },
  modeChip: { flex: 1, paddingVertical: 8, borderRadius: 10, borderWidth: 1, alignItems: 'center' },
});
